"""Writes the generated half of REFERENCE.md: every call and effect of Obsidian API, from the source and the
comments above each one. Everything above the marker line is written by hand and left alone.

Usage: python tools/reference.py           rewrite REFERENCE.md
       python tools/reference.py --check   exit 1 if REFERENCE.md isn't up to date (the release workflow runs this)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "REFERENCE.md"
MARKER = "<!-- Everything below is generated by tools/reference.py from the source. Don't edit it by hand. -->"

# Functions a module keeps for main.lua and its own hooks. They're public in Lua, but not for mods.
INTERNAL = {
    "bots": {"tick", "drive_all", "draw_names", "install"},
    "combat": {"health", "shield", "command_master", "filter_slave_command"},
    "console": {"install"},
    "custom": {"install", "get", "tick"},
    "effects": {"tick", "pause", "resume"},
    "edits": {"pause", "resume"},
    "enemies": {"tick"},
    "events": {"tick"},
    "game": {"tick", "plugin", "session_mode"},
    "gear": {"tick"},
    "map": {"install", "draw", "reset"},
    "menu": {"install", "frame", "runner", "panel_mouse"},
    "mod_settings": {"install", "tick", "run_chosen"},
    "world": {"install", "tick"},
    "capture": {"tick", "reset", "hold_screen", "find_window", "save_now", "area"},
    "mission": {"on_mission_start_update", "install"},
    "music": {"tick", "after_machine_enter"},
    "stratagems": {"find", "call_unowned", "define", "custom"},
}
# Calls one module makes public under another table's name.
RENAMED = {"custom": ("stratagems", {"define": "define", "list": "custom", "unlock": "unlock", "lock": "lock",
                                      "is_unlocked": "is_unlocked"})}
OBJECTS = {"Bot": "bot", "Drone": "drone", "Prop": "prop", "Marker": "marker", "Page": "page", "Panel": "panel", "LightHandle": "light"}

FUNC = re.compile(r"^function (M\.camera|M|Bot|Drone|Prop|Marker|Page|Panel|LightHandle)[.:]([A-Za-z_]\w*)\s*\(([^)]*)\)")
CONST = re.compile(r"^M\.([A-Z][A-Z_]*)\s*=")
ALIAS = re.compile(r"^M\.([a-z_]\w*)\s*=\s*([A-Za-z_][\w.]*)\s*$")
EFFECT = re.compile(r'(?:effects\.define\(\{\s*id\s*=\s*|field_effect\(|switch_effect\()"([a-z_]+)"')


def exported():
    """api name -> module file stem, from main.lua's returned table and its obsidian.module lines."""
    text = (ROOT / "main.lua").read_text(encoding="utf-8")
    files = dict(re.findall(r'^local (\w+) = obsidian\.module\("lib/(\w+)"\)', text, re.M))
    tail = text[text.rindex("return {"):]
    out = {}
    for name, var in re.findall(r"^\t(\w+) = (?:guard\()?(\w+)", tail, re.M):
        if var in files:
            out[name] = files[var]
    return out


def read_module(stem):
    lines = (ROOT / "lib" / (stem + ".lua")).read_text(encoding="utf-8").splitlines()
    head = []
    for line in lines:
        if not line.startswith("--"):
            break
        head.append(line[2:].strip())
    entries, effects, comment = [], [], []
    for line in lines[len(head):]:
        s = line.rstrip()
        if s.startswith("--"):
            comment.append(s.lstrip("-").strip())
            continue
        note = " ".join(c for c in comment if c)
        comment = []
        m = FUNC.match(s)
        if m:
            entries.append((m.group(1), m.group(2), m.group(3).strip(), note))
            continue
        e = EFFECT.search(s)
        if e:
            effects.append((e.group(1), note))
            continue
        c = CONST.match(s) or ALIAS.match(s)
        if c:
            entries.append(("M", c.group(1), None, note))
    return " ".join(h for h in head if h).strip(), entries, effects


def render():
    version = json.loads((ROOT / "obsidian.json").read_text(encoding="utf-8"))["version"]
    tables = exported()
    calls = {name: [] for name in tables}
    heads = {}
    all_effects = []
    for name, stem in sorted(tables.items()) + [("custom", "custom")]:
        head, entries, effects = read_module(stem)
        if name in tables:
            heads[name] = head
        target, renames = RENAMED.get(stem, (name, None))
        skip = INTERNAL.get(stem, set())
        for owner, fn, args, note in entries:
            if renames is not None:
                if owner != "M" or fn not in renames:
                    continue
                fn = renames[fn]
            elif owner == "M" and fn in skip:
                continue
            calls.setdefault(target, []).append((owner, fn, args, note))
        all_effects += [(eid, note, name) for eid, note in effects]

    out = [MARKER, "", f"## Every call (Obsidian API {version})", ""]
    out.append("Each table of `api`, its calls in the order of the source, and the comment above each one. "
               "`bot:`, `drone:`, `prop:`, `marker:` and `page:` are methods of what `api.bots.add`, `api.gear.add_drone`, "
               "`api.world.prop`, `api.map.marker` and `api.mod_settings.page` answer, and under `api.menu`, of the page a build gets. "
               "Where this list and the guide above disagree, this list is right.")
    for name in sorted(calls):
        out += ["", f"### api.{name}", ""]
        if heads.get(name):
            out += [heads[name], ""]
        for owner, fn, args, note in calls[name]:
            if owner == "M":
                prefix = f"api.{name}."
            elif owner == "M.camera":
                prefix = f"api.{name}.camera."
            else:
                prefix = OBJECTS[owner] + ":"
            sig = f"`{prefix}{fn}({args})`" if args is not None else f"`{prefix}{fn}`"
            out.append(f"- {sig}" + (f": {note}" if note else ""))
    out += ["", "### Effects", "", "Every effect id, for `api.effects.set(id, value)`, with the module that defines it. "
            "A trailing `_` takes a name after it: `bus_music`, `shading_exposure`, `immune_fire`.", ""]
    for eid, note, module in sorted(all_effects):
        out.append(f"- `{eid}` ({module})" + (f": {note}" if note else ""))
    return "\n".join(out) + "\n"


def main():
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    head = current.split(MARKER)[0] if MARKER in current else current
    new = head.rstrip("\n") + "\n\n" + render()
    if "--check" in sys.argv:
        if new != current:
            print("REFERENCE.md is out of date: run python tools/reference.py")
            sys.exit(1)
        print("REFERENCE.md is up to date")
        return
    OUT.write_text(new, encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
